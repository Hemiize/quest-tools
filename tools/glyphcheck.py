"""Finds characters the Windows console font (Consolas, WGL4 set) cannot draw.

    python tools/glyphcheck.py questtools
"""
import sys, unicodedata
from pathlib import Path
sys.stdout.reconfigure(encoding="utf-8")
ranges = [(0x20,0x7e),(0xa0,0x17f),(0x2010,0x2022),(0x2026,0x2026),(0x2030,0x203a),(0x2190,0x2195),(0x21a8,0x21a8),
          (0x2219,0x221a),(0x221e,0x221f),(0x2229,0x2229),(0x2248,0x2248),(0x2260,0x2265),(0x2302,0x2302),(0x2310,0x2310),
          (0x2320,0x2321),(0x2500,0x2500),(0x2502,0x2502),(0x250c,0x250c),(0x2510,0x2510),(0x2514,0x2514),(0x2518,0x2518),
          (0x251c,0x251c),(0x2524,0x2524),(0x252c,0x252c),(0x2534,0x2534),(0x253c,0x253c),(0x2550,0x256c),(0x2580,0x2580),
          (0x2584,0x2584),(0x2588,0x2588),(0x258c,0x258c),(0x2590,0x2593),(0x25a0,0x25a1),(0x25aa,0x25ac),(0x25b2,0x25b2),
          (0x25ba,0x25ba),(0x25bc,0x25bc),(0x25c4,0x25c4),(0x25ca,0x25cb),(0x25cf,0x25cf),(0x25d8,0x25d9),(0x25e6,0x25e6),
          (0x263a,0x263c),(0x2640,0x2640),(0x2642,0x2642),(0x2660,0x2660),(0x2663,0x2663),(0x2665,0x2666),(0x266a,0x266b),
          (0x20ac,0x20ac),(0x2122,0x2122),(0xd7,0xd7)]
ok = set()
for a, b in ranges:
    ok.update(range(a, b + 1))
found = {}
for f in Path(sys.argv[1]).rglob("*.py"):
    for i, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
        for ch in line:
            if ord(ch) > 127 and ord(ch) not in ok:
                found.setdefault(ch, set()).add(f.name)
for ch, files in sorted(found.items()):
    print(f"{ch} U+{ord(ch):04X} {unicodedata.name(ch, '?'):38} {', '.join(sorted(files))}")
print("total", len(found))
